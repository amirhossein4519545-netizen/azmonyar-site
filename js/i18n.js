  var lang = 'fa';

  function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, function (m, key) {
      return Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : m;
    });
  }

  var i18n = {
    dict: dict,

    get lang() { return lang; },

    setLang: function (next) {
      lang = dict[next] ? next : 'fa';
      try { localStorage.setItem('azmonyar.lang', lang); } catch (e) { /* ignore */ }
      var html = document.documentElement;
      html.lang = lang;
      html.dir = lang === 'fa' ? 'rtl' : 'ltr';
    },

    init: function () {
      var saved = null;
      try { saved = localStorage.getItem('azmonyar.lang'); } catch (e) { /* ignore */ }
      i18n.setLang(saved || 'fa');
    },

    t: function (key, vars) {
      var table = dict[lang] || dict.fa;
      var str = table[key];
      if (str === undefined) str = dict.fa[key];
      if (str === undefined) return key;
      return interpolate(str, vars);
    },

    num: function (value) {
      var n = Number(value);
      if (!isFinite(n)) return String(value);
      try { return n.toLocaleString(lang === 'fa' ? 'fa-IR' : 'en-US'); }
      catch (e) { return String(n); }
    },

    date: function (value, withTime) {
      if (!value) return '—';
      var d = value instanceof Date ? value : new Date(value);
      if (isNaN(d.getTime())) return '—';
      var opts = withTime
        ? { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }
        : { year: 'numeric', month: 'short', day: 'numeric' };
      try {
        return d.toLocaleString(lang === 'fa' ? 'fa-IR' : 'en-GB', opts);
      } catch (e) {
        return d.toISOString().slice(0, 10);
      }
    },

    className: function (cls) {
      if (!cls) return i18n.t('class.gradeOther');
      var name = lang === 'fa' ? cls.name : (cls.nameEn || cls.name);
      return name || cls.name;
    },

    text: function (obj, base) {
      if (!obj) return '';
      if (lang === 'fa') return obj[base] || (obj[base + 'En'] || '');
      return obj[base + 'En'] || obj[base] || '';
    }
  };

  i18n.checkKeys = function () {
    var missing = [];
    Object.keys(dict.fa).forEach(function (k) {
      if (dict.en[k] === undefined) missing.push('en:' + k);
    });
    Object.keys(dict.en).forEach(function (k) {
      if (dict.fa[k] === undefined) missing.push('fa:' + k);
    });
    if (missing.length && window.console) console.warn('[i18n] missing keys:', missing);
    return missing;
  };

  window.AZ = window.AZ || {};
  window.AZ.i18n = i18n;
